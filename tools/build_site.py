#: Two mean deviations closer than this are not distinguishable by this
#: benchmark, so neither code is credited with the difference.
#:
#: The two codes agree on the heat curves to a median 0.019%, and they are
#: stepped to times that differ by up to 0.82% on the 1996exp_7hour campaign,
#: so a gap of a few hundredths of a point says nothing about either. Without a
#: band, 130 experiments produce 130 verdicts where about 20 are real: 85 of
#: the pairs differ by less than 0.05 percentage points.
TIE_POINTS = 0.25


def head_to_head(yani, fispact, band=TIE_POINTS):
    """(yani closer, FISPACT closer, tied) over paired mean deviations."""
    difference = yani - fispact
    return (int(np.sum(difference < -band)),
            int(np.sum(difference > band)),
            int(np.sum(np.abs(difference) <= band)))


def fns_summary_figure(documents, destination):
    """Mean deviation, yani against FISPACT-II, one point per experiment.

    A paired scatter rather than two histograms: the two codes ran the same 130
    experiments with the same library, so the pairing is real and throwing it
    away to plot two distributions would hide which experiments moved. Below
    the diagonal is yani closer to the measurement.
    """
    apples = documents[libraries.APPLES_TO_APPLES]["results"]
    pairs = [(key, entry["fispact_metrics"]["mean_deviation_percent"],
              entry["metrics"]["mean_deviation_percent"])
             for key, entry in sorted(apples.items())
             if "fispact_metrics" in entry]
    if not pairs:
        return None, 0, 0, 0, 0
    fispact = np.array([p[1] for p in pairs])
    yani = np.array([p[2] for p in pairs])
    yani_wins, fispact_wins, ties = head_to_head(yani, fispact)

    def draw(palette):
        figure, axes = plotting.plt.subplots(figsize=(6.4, 6.4))
        figure.patch.set_facecolor(palette["surface"])
        limit = [0.3, max(fispact.max(), yani.max()) * 1.6]
        axes.plot(limit, limit, "-", color=palette["grid"], linewidth=1.5, zorder=1)
        axes.fill_between(limit, limit, [limit[1]] * 2, color=palette["yani"],
                          alpha=0.06, zorder=0)
        axes.scatter(fispact, yani, s=34, color=palette["yani"], alpha=0.85,
                     edgecolor=palette["surface"], linewidth=0.8, zorder=3)
        axes.set_xscale("log")
        axes.set_yscale("log")
        axes.set_xlim(limit)
        axes.set_ylim(limit)
        axes.set_xlabel("FISPACT-II mean deviation [%]")
        axes.set_ylabel("yani mean deviation [%]")
        axes.set_title(
            f"FNS decay heat, both codes on TENDL-2017\n"
            f"{yani_wins} closer with yani, {fispact_wins} with FISPACT-II, "
            f"{ties} tied within {TIE_POINTS} points",
            color=palette["text"], fontsize=11, pad=12)
        # The shaded half is the claim; saying which half is which beats a
        # legend entry for a region.
        axes.text(0.04, 0.96, "yani closer", transform=axes.transAxes,
                  color=palette["muted"], fontsize=9, va="top")
        axes.text(0.96, 0.04, "FISPACT-II closer", transform=axes.transAxes,
                  color=palette["muted"], fontsize=9, ha="right")
        plotting.style(axes, palette)
        return figure

    plotting.both_modes(draw, destination)
    return destination, yani_wins, fispact_wins, ties, len(pairs)


def fns_case_figure(key, documents, destination, openmc=None):
    """One experiment: the measurement, FISPACT-II, and every yani combination.

    The top panel is the decay-heat curve and the bottom is C/E against the
    same time axis, which is where a curve that is close on a log scale but
    systematically high shows itself.
    """
    apples_name = libraries.APPLES_TO_APPLES
    entry = documents[apples_name]["results"][key]
    times = np.array(entry["times"])
    measured = np.array(entry["measured_uW_per_g"])
    uncertainty = np.array(entry["measured_uncertainty_uW_per_g"])
    calculated = np.array(entry["yani_uW_per_g"])
    # None on a result written before the sweep carried covariance, and None on
    # a sweep that chose not to, so the figure has to work either way.
    sigma = (np.array(entry["yani_sigma_uW_per_g"])
             if entry.get("yani_sigma_uW_per_g") else None)

    # The best other combination, by mean deviation, is drawn as one extra line.
    # All ten would be unreadable, and the table underneath carries them all.
    alternatives = [
        (name, document["results"][key])
        for name, document in ordered(documents)
        if name != apples_name and key in document["results"]
    ]
    best = min(alternatives,
               key=lambda pair: pair[1]["metrics"]["mean_deviation_percent"],
               default=None)

    def draw(palette):
        figure, (top, bottom) = plotting.plt.subplots(
            2, 1, figsize=(7.6, 7.2), sharex=True,
            gridspec_kw={"height_ratios": [3, 1.4]})
        figure.patch.set_facecolor(palette["surface"])

        top.errorbar(times, measured, yerr=uncertainty, fmt="o",
                     color=palette["measurement"], markersize=plotting.MARKER_SIZE,
                     capsize=3, linewidth=1.2, label="measurement", zorder=5)
        if entry.get("fispact_uW_per_g"):
            top.plot(times, entry["fispact_uW_per_g"], "-",
                     color=palette["fispact"], linewidth=plotting.LINE_WIDTH,
                     label=f"FISPACT-II, {apples_name}", zorder=3)
        top.plot(times, entry["yani_uW_per_g"], "-", color=palette["yani"],
                 linewidth=plotting.LINE_WIDTH, label=f"yani, {apples_name}",
                 zorder=4)
        if sigma is not None:
            # Drawn as a band rather than as error bars: the measurement owns
            # the error-bar idiom on this figure, and a second set of them on a
            # 21-point log curve is unreadable.
            top.fill_between(times, calculated - sigma, calculated + sigma,
                             color=palette["yani"], alpha=0.20, linewidth=0,
                             label="yani, nuclear-data 1 sigma", zorder=2)
        if best is not None:
            top.plot(times, best[1]["yani_uW_per_g"], "--",
                     color=palette["yani_best"], linewidth=plotting.LINE_WIDTH,
                     label=f"yani, {best[0]}", zorder=4)
        for label, entries in (openmc or {}).items():
            if key in entries:
                top.plot(times, entries[key]["openmc_uW_per_g"], ":",
                         color=palette["openmc"], linewidth=plotting.LINE_WIDTH,
                         label=f"OpenMC, {label}", zorder=3)

        top.set_yscale("log")
        top.set_ylabel("specific decay heat [µW/g]")
        top.set_title(
            f"FNS {entry['case']}, {entry['experiment']}",
            color=palette["text"], fontsize=12, pad=10)
        legend = top.legend(loc="best", frameon=False, fontsize=9)
        for text in legend.get_texts():
            text.set_color(palette["text"])
        plotting.style(top, palette)

        bottom.axhline(1.0, color=palette["muted"], linewidth=1)
        fraction = over_measured(uncertainty, measured)
        bottom.fill_between(times, 1 - fraction, 1 + fraction,
                            color=palette["measurement"], alpha=0.12,
                            label="measurement uncertainty")
        if entry.get("fispact_uW_per_g"):
            bottom.plot(times, over_measured(entry["fispact_uW_per_g"], measured),
                        "o-", color=palette["fispact"], markersize=4, linewidth=1.5)
        if sigma is not None:
            ratio = over_measured(calculated, measured)
            band = over_measured(sigma, measured)
            bottom.fill_between(times, ratio - band, ratio + band,
                                color=palette["yani"], alpha=0.20, linewidth=0,
                                label="yani, nuclear-data 1 sigma")
        bottom.plot(times, over_measured(entry["yani_uW_per_g"], measured), "o-",
                    color=palette["yani"], markersize=4, linewidth=1.5)
        if best is not None:
            bottom.plot(times, over_measured(best[1]["yani_uW_per_g"], measured),
                        "o--", color=palette["yani_best"], markersize=4, linewidth=1.5)
        for entries in (openmc or {}).values():
            if key in entries:
                bottom.plot(times,
                            over_measured(entries[key]["openmc_uW_per_g"], measured),
                            "o:", color=palette["openmc"], markersize=4,
                            linewidth=1.5)
        bottom.set_xscale("log")
        bottom.set_ylabel("C / E")
        bottom.set_xlabel(f"time after shutdown [{entry['time_unit']}]")
        legend = bottom.legend(loc="best", frameon=False, fontsize=9)
        for text in legend.get_texts():
            text.set_color(palette["text"])
        plotting.style(bottom, palette)

        figure.tight_layout()
        return figure

    plotting.both_modes(draw, destination)
    return best[0] if best else None


def fns_page(documents):
    if not documents:
        return "# FNS decay heat\n\nNo results yet.\n"

    apples_name = libraries.APPLES_TO_APPLES
    if apples_name not in documents:
        return "# FNS decay heat\n\nNo results yet.\n"
    apples = documents[apples_name]

    FIGURES.mkdir(parents=True, exist_ok=True)
    summary_path, yani_wins, fispact_wins, ties, paired = fns_summary_figure(
        documents, FIGURES / "fns-summary.png")

    lines = [GENERATED, "# FNS decay heat", "", PROSE["fns_decay_heat"], ""]
    lines += coverage_note(documents, TOTAL_FNS_EXPERIMENTS, "experiments",
                           "python tools/run_all.py")

    # --- headline -----------------------------------------------------------
    lines += ["## yani against FISPACT-II, same data", ""]
    if summary_path:
        lines += [plotting.image_markup(summary_path,
                                        "yani against FISPACT-II mean deviation"), ""]
        lines += [
            f"On the {paired} experiments the archive publishes a FISPACT-II "
            f"curve for, both codes reading TENDL-2017 cross sections and "
            f"UKAEA's decay_2012 decay data, yani is closer to the measurement "
            f"on **{yani_wins}**, FISPACT-II on **{fispact_wins}**, and "
            f"**{ties}** are tied within {TIE_POINTS} percentage points.", "",
            f"The tie band is not a courtesy. The two codes agree on the heat "
            f"curves to a median 0.019%, which is far below the 0 to 0.8% "
            f"error introduced by the two being stepped to slightly different "
            f"times, so a difference of a few hundredths of a point is not "
            f"something this benchmark can resolve. Counted without a band, "
            f"every experiment produces a verdict and almost none of them "
            f"means anything.", ""]

    rows = [(key, entry) for key, entry in sorted(apples["results"].items())]
    yani_dev = np.array([e["metrics"]["mean_deviation_percent"] for _, e in rows])
    paired_rows = [(k, e) for k, e in rows if "fispact_metrics" in e]
    fispact_dev = np.array(
        [e["fispact_metrics"]["mean_deviation_percent"] for _, e in paired_rows])
    paired_yani = np.array(
        [e["metrics"]["mean_deviation_percent"] for _, e in paired_rows])

    lines += ["| code | experiments | median mean deviation | within 10% | within 20% |",
              "| --- | ---: | ---: | ---: | ---: |"]
    lines += [f"| yani, {apples_name} | {len(paired_yani)} | "
              f"{np.median(paired_yani):.1f}% | "
              f"{int(np.sum(paired_yani <= 10))} | {int(np.sum(paired_yani <= 20))} |"]
    lines += [f"| FISPACT-II, {apples_name} | {len(fispact_dev)} | "
              f"{np.median(fispact_dev):.1f}% | "
              f"{int(np.sum(fispact_dev <= 10))} | {int(np.sum(fispact_dev <= 20))} |"]
    lines += ["", "Both rows are the same experiments with the same data: "
                  "TENDL-2017 cross sections, reaction topology and isomeric "
                  "branching, and UKAEA's decay_2012 decay library, fetched from "
                  "UKAEA's own distribution and converted locally. What separates "
                  "the rows is the code, and the two agree on the heat of every "
                  "experiment to a median 0.01%; the residuals are TENDL-2017 "
                  "isomer partials that do not sum to the total (Ir), natural "
                  "abundances (Pt, Mo) and a short-lived isomer FISPACT-II's "
                  "nuclide index leaves out (Hf). The `tendl-2017` line below is "
                  "the same neutron data with ENDF/B-VIII.1 decay data, which is "
                  "what yani users get by default. See the methodology page.", ""]

    # --- every combination --------------------------------------------------
    lines += ["## Every nuclear-data combination", "",
              "The row above is the comparison. These are the answer to a "
              "different question: given a free choice of data, how close does "
              "this get?", "",
              "| combination | cross sections | reactions | branching | decay | "
              "solved | median mean deviation |",
              "| --- | --- | --- | --- | --- | ---: | ---: |"]
    for name, document in ordered(documents):
        combination = libraries.BY_NAME[name]
        deviations = np.array([e["metrics"]["mean_deviation_percent"]
                               for e in document["results"].values()])
        if not deviations.size:
            continue
        lines += [f"| `{name}` | {combination.cross_sections} | "
                  f"{combination.reactions} | {combination.branching} | "
                  f"{combination.decay} | {len(deviations)} | "
                  f"{np.median(deviations):.1f}% |"]
    lines += [""]

    for name, document in ordered(documents):
        lines += [f"**`{name}`** -- {libraries.BY_NAME[name].note}", ""]

    # --- openmc -------------------------------------------------------------
    openmc = {label: document["results"]
              for label, document in load_openmc("fns_decay_heat").items()}
    if openmc:
        lines += ["## OpenMC on the same experiments", "", PROSE["openmc"], ""]
        lines += ["| code | experiments | median mean deviation |",
                  "| --- | ---: | ---: |"]
        for label, entries in openmc.items():
            shared = [k for k in entries if k in apples["results"]]
            values = np.array([entries[k]["metrics"]["mean_deviation_percent"]
                               for k in shared])
            against = np.array(
                [apples["results"][k]["metrics"]["mean_deviation_percent"]
                 for k in shared])
            lines += [f"| OpenMC, `{label}` | {len(values)} | "
                      f"{np.median(values):.1f}% |"]
            lines += [f"| yani, `{apples_name}`, same experiments | "
                      f"{len(against)} | {np.median(against):.1f}% |"]
        document = list(load_openmc("fns_decay_heat").values())[0]
        lines += ["", f"OpenMC {document.get('openmc_version', '?')}, chain "
                      f"`{pathlib.Path(document.get('chain_file', '?')).name}`, "
                      f"cross sections "
                      f"`{pathlib.Path(document.get('cross_sections', '?')).name}`.",
                  ""]

    # --- per experiment -----------------------------------------------------
    lines += ["## Every experiment", "",
              f"One figure per experiment, {len(rows)} of them. The solid orange "
              f"line is the apples-to-apples run and the dashed line is whichever "
              f"other combination scored best on that foil.", ""]

    for key, entry in rows:
        figure_name = f"fns-{entry['case']}-{entry['experiment']}.png"
        best = fns_case_figure(key, documents, FIGURES / figure_name, openmc)
        metrics = entry["metrics"]
        lines += [f"### {entry['case']}, {entry['experiment']}", ""]
        lines += [plotting.image_markup(FIGURES / figure_name,
                                        f"FNS {entry['case']} {entry['experiment']}"), ""]

        lines += ["| line | mean deviation | median C/E | max deviation |",
                  "| --- | ---: | ---: | ---: |"]
        lines += [f"| yani, `{apples_name}` | {metrics['mean_deviation_percent']:.1f}% | "
                  f"{metrics['median_ratio']:.3f} | "
                  f"{metrics['max_deviation_percent']:.1f}% |"]
        if "fispact_metrics" in entry:
            fispact_metrics = entry["fispact_metrics"]
            lines += [f"| FISPACT-II, `{apples_name}` | "
                      f"{fispact_metrics['mean_deviation_percent']:.1f}% | "
                      f"{fispact_metrics['median_ratio']:.3f} | "
                      f"{fispact_metrics['max_deviation_percent']:.1f}% |"]
        if best:
            best_metrics = documents[best]["results"][key]["metrics"]
            lines += [f"| yani, `{best}` | "
                      f"{best_metrics['mean_deviation_percent']:.1f}% | "
                      f"{best_metrics['median_ratio']:.3f} | "
                      f"{best_metrics['max_deviation_percent']:.1f}% |"]
        lines += ["",
                  f"Measurement uncertainty "
                  f"{metrics['median_measurement_sigma_percent']:.1f}% (median). "
                  f"Heat carried by {', '.join(entry['leaders'])}.", ""]

    lines += ["## Reproducing this page", "",
              "```bash", f"python benchmarks/fns_decay_heat/sweep.py", "```", "",
              f"yani {apples.get('yani_version', 'unknown')}. "
              f"Benchmark data from the IAEA CoNDERC archive, distilled by "
              f"`benchmarks/fns_decay_heat/build_data.py`.", ""]
    return "\n".join(lines)


