def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--benchmark", action="append", default=[])
    args = parser.parse_args()

    wanted = args.benchmark or ["fns_decay_heat", "effective_cross_sections"]
    builders = {
        "fns_decay_heat": (fns_page, "fns-decay-heat.md"),
        "effective_cross_sections": (ecs_page, "effective-cross-sections.md"),
    }

    DOCS.mkdir(parents=True, exist_ok=True)
    for benchmark in wanted:
        builder, filename = builders[benchmark]
