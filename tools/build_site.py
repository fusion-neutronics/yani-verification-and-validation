#!/usr/bin/env python3
"""Turn the committed sweep results into the benchmark pages and their figures.

    python tools/build_site.py
    python tools/build_site.py --benchmark fns_decay_heat

Reads `benchmarks/*/results/*.json`, writes `docs/benchmarks/*.md` and
`docs/benchmarks/figures/`. Needs numpy and matplotlib and nothing else: no
yani, no nuclear data, no network. That is deliberate, so the site can be built
in CI from the repository alone, and so a page can never quietly disagree with
the result file it claims to display.

Every generated page carries a header saying it is generated. Edit this script
or the benchmark's prose in `PROSE` below, not the markdown.
"""

