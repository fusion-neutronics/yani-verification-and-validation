# What a complete run covers, so a partial page can say so. Read from the
# committed benchmark data rather than written down, since writing it down is
# how it comes to disagree with the data.
def _total(path, key):
    document = json.loads(path.read_text())
    if key == "fns":
        return sum(len(entries) for entries in document["cases"].values())
    return len(document["reactions"])


TOTAL_FNS_EXPERIMENTS = _total(
    ROOT / "benchmarks" / "fns_decay_heat" / "data" / "fns_data.json", "fns")
TOTAL_ECS_REACTIONS = _total(
    ROOT / "benchmarks" / "effective_cross_sections" / "data" / "rr_data.json", "ecs")


def coverage_note(documents, expected_cases, unit, command):
    """A banner naming what has not been run yet, or nothing when it all has.

    A page built from a partial sweep looks exactly like a page built from a
    complete one, except that some rows are missing, and a reader has no way to
    tell an unrun combination from one that failed. So the page says which it
    is, and how to finish it.

    A combination that ran every case and had some refused by its library is
    **not** partial, and saying "draft" over it would be wrong: nothing is
    waiting to be computed, the library does not publish those elements and
    never will. `solved + refused == expected` is what separates the two, and
    the refusals get their own note rather than the warning banner.

    The refusals are counted off `failures`, which both benchmarks write, rather
    than off the `failed` total, which only the FNS sweep writes. Counting the
    total instead reads every effective cross-section refusal as unfinished
    work, which would hold a draft banner over a page that is complete: the two
    FENDL combinations solve 321 of 365 and can never solve the other 44,
    because FENDL-3.2d does not evaluate those nuclides. On the FNS files, where
    both fields exist, they agree.
    """
    unrun, refused = [], []
    for combination in libraries.COMBINATIONS:
        document = documents.get(combination.name)
        if document is None:
            unrun.append((combination.name, 0))
            continue
        solved = len(document["results"])
        attempted = solved + len(document.get("failures", {}))
        if attempted < expected_cases:
            unrun.append((combination.name, solved))
        elif solved < expected_cases:
            refused.append((combination.name, expected_cases - solved))

    lines = []
    if unrun:
        lines += ['!!! warning "Draft: this page is built from a partial run"', ""]
        lines += [f"    {len(libraries.COMBINATIONS) - len(unrun)} of "
                  f"{len(libraries.COMBINATIONS)} nuclear-data combinations have "
                  f"been run, out of {expected_cases} {unit} each.", ""]
        for name, count in unrun:
            state = "not run" if count == 0 else f"{count} of {expected_cases}"
            lines += [f"    * `{name}` -- {state}"]
        lines += ["", f"    To finish it: `{command}`", ""]

    if refused:
        lines += ['!!! note "Some libraries do not cover every case"', ""]
        lines += [f"    These ran every one of the {expected_cases} {unit} and "
                  f"had some refused, because the library publishes no "
                  f"evaluation for an element the case needs. That is a gap in "
                  f"the library rather than a gap in this page.", ""]
        for name, count in refused:
            lines += [f"    * `{name}` -- {count} refused, "
                      f"{expected_cases - count} scored"]
        lines += [""]
    return lines


def over_measured(values, measured):
    """`values / measured`, with a gap wherever there is no measurement.

    A few experiments carry rows whose measured heat is exactly zero. Those are
    not measurements of zero; they are places the benchmark has no value, and
    the scoring already excludes them. Dividing by them would put an infinity on
    the C/E panel and stretch its axis until every real point is a flat line, so
    they come through as NaN and matplotlib leaves a gap.
    """
    values = np.asarray(values, dtype=float)
    measured = np.asarray(measured, dtype=float)
    return np.divide(values, measured, out=np.full(values.shape, np.nan),
                     where=measured > 0)


def load_results(benchmark):
    """{combination name: document} for one benchmark, newest run wins."""
    directory = ROOT / "benchmarks" / benchmark / "results"
    documents = {}
    for path in sorted(directory.glob("*.json")):
        if path.stem not in libraries.BY_NAME:
            continue
        documents[path.stem] = json.loads(path.read_text())
    return documents


def load_openmc(benchmark):
    """{chain label: document} for any OpenMC runs of this benchmark.

    Kept separate from the yani combinations rather than folded in beside them:
    an OpenMC run is named by its chain file, not by one of the five-way
    combinations, and there is no chain published that would let it stand on the
    apples-to-apples line at all.
    """
    directory = ROOT / "benchmarks" / benchmark / "results"
    documents = {}
    for path in sorted(directory.glob("openmc-*.json")):
        document = json.loads(path.read_text())
        documents[document.get("chain_label", path.stem)] = document
    return documents


def ordered(documents):
    """Combinations in the order they are declared, apples-to-apples first."""
    return [(c.name, documents[c.name]) for c in libraries.COMBINATIONS
            if c.name in documents]


